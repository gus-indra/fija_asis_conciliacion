QUERY_EJECT= '''
WITH TIPTRABAJO AS
 (SELECT TTO.TIPTRA
    FROM DWS.SA_TIPTRABAJO TTO
   WHERE REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(CAMBIO DE PLAN)', 1, 1) > 0
     AND REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(BAJA|PAQUETES)', 1, 1) = 0
     AND REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(HFC|FTTH|WLL)', 1, 1) > 0),
MOTOT AS
 (SELECT MT.CODMOTOT
    FROM DWS.SA_MOTOT MT
   WHERE REGEXP_INSTR(UPPER(MT.DESCRIPCION), '(CON VISITA TECNICA)', 1, 1) > 0),
CLIENTES_SGA AS
 (SELECT /*+parallel (4)*/
  DISTINCT ST.CODSOLOT,
           ST.CUSTOMER_ID,
           ST.CODCLI,
           ST.FECUSU,
           ST.COD_ID       AS CO_ID,
           ST.ESTSOL,
           EST.DESCRIPCION AS DSC_ESTSOL,
           ST.TIPTRA,
           TTO.DESCRIPCION AS DSC_TIPTRA,
           ST.CODMOTOT,
           SM.DESCRIPCION  AS DSC_CODMOTOT
    FROM DMRED.SGAPRD_SOLOT ST
   INNER JOIN DWS.SA_ESTSOL EST
      ON EST.ESTSOL = ST.ESTSOL
   INNER JOIN DWS.SA_TIPTRABAJO TTO
      ON TTO.TIPTRA = ST.TIPTRA
   INNER JOIN TIPTRABAJO TT
      ON TT.TIPTRA = TTO.TIPTRA
   INNER JOIN DWS.SA_MOTOT SM
      ON SM.CODMOTOT = ST.CODMOTOT
   INNER JOIN MOTOT MT
      ON MT.CODMOTOT = SM.CODMOTOT
   WHERE ST.CUSTOMER_ID IS NOT NULL
     AND EST.ESTSOL IN (17)
     AND ST.CODCLI NOT IN
         (SELECT VTC.CODCLI
            FROM DWS.SA_VTATABCLI VTC
           WHERE VTC.NOMCLI LIKE '% DEMO %')
     AND TRUNC(ST.FECUSU) <= TRUNC(SYSDATE - 1)
     AND NOT EXISTS (SELECT /*+parallel (4)*/
           1
            FROM DWS.SA_AGENDAMIENTO SA
           WHERE SA.CODSOLOT = ST.CODSOLOT))
SELECT /*+parallel (4)*/
 CS.CUSTOMER_ID,
 CS.CO_ID,
 CS.CODSOLOT,
 CS.TIPTRA,
 CS.DSC_TIPTRA,
 CS.ESTSOL,
 CS.DSC_ESTSOL,
 CS.CODMOTOT,
 CS.DSC_CODMOTOT,
 CS.CODCLI,
 CS.FECUSU,
 CASE
   WHEN CH.CH_STATUS IS NOT NULL THEN
    'AS_IS'
   ELSE
    'TO_BE'
 END AS PLATAFORMA
  FROM CLIENTES_SGA CS
  LEFT JOIN DM.V_CONTRACT_HISTORY CH
    ON CH.CO_ID = CS.CO_ID
  LEFT JOIN DMRED.BSCSIX_CONTRACT_ALL CA
    ON CA.CO_ID = CS.CO_ID
'''

