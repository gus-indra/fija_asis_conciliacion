OBTENER_BASE_SGA = '''
WITH BASE_CLIENTES_SGA AS
(SELECT DISTINCT A.CUSTOMER_ID,
                C.CODINSSRV,
                C.NUMERO,
                C.TIPSRV,
                C.ESTINSSRV,
                D.DSCTIPSRV
FROM SOLOT A, VTATABSLCFAC B, INSSRV C, TYSTIPSRV D
WHERE A.NUMSLC = B.NUMSLC
    AND C.TIPSRV = D.TIPSRV
    AND B.NUMSLC = C.NUMSLC
    AND A.CUSTOMER_ID IS NOT NULL
    AND C.TIPSRV IN ('0004', '0062', '0006')
    AND C.ESTINSSRV IN (1)),

BASE_CLIENTES_SGA_2 AS
(SELECT B.CUSTOMER_ID, B.TIPSRV, B.DSCTIPSRV, B.NUMERO, COUNT(1) CANTIDAD
FROM BASE_CLIENTES_SGA B
WHERE LENGTH(B.CUSTOMER_ID) <> 9
GROUP BY B.CUSTOMER_ID, B.TIPSRV, B.DSCTIPSRV, B.NUMERO
HAVING COUNT(1) > 1
ORDER BY B.CUSTOMER_ID, B.TIPSRV, B.DSCTIPSRV, B.NUMERO)

SELECT * FROM BASE_CLIENTES_SGA_2 B
'''
