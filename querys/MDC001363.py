OBTENER_BASE = '''
SELECT /*+ PARALLEL(2) */ 
    DISTINCT
    D.CUSTOMER_ID,
    D.COD_ID, 
    D.FECULTEST,
    A.PID,
    B.FECINI,
    B.FECFIN,
    B.TIPSRV,
    T.DSCTIPSRV,
    C.FLGPRINC,
    B.CODINSSRV,
    C.CODSRV, 
    C.CODUSU,
    E.DSCSRV, 
    C.ESTINSPRD,
    D.TIPTRA,
    R.DESCRIPCION
FROM SOLOTPTO A
INNER JOIN SOLOT  D                     ON A.CODSOLOT = D.CODSOLOT
INNER JOIN INSPRD C                     ON C.CODINSSRV = A.CODINSSRV AND A.PID = C.PID
INNER JOIN INSSRV B                     ON C.CODINSSRV = B.CODINSSRV AND C.CODSRV = B.CODSRV
INNER JOIN TYSTABSRV E                  ON E.CODSRV = C.CODSRV
INNER JOIN TYSTIPSRV T                  ON B.TIPSRV = T.TIPSRV
INNER JOIN TIPTRABAJO R                 ON D.TIPTRA = R.TIPTRA 
INNER JOIN INTRAWAY.CONFIGURACION_ITW F ON TO_CHAR(F.IDCONFIGITW) = E.CODIGO_EXT
WHERE C.FLGPRINC = 1
  AND C.ESTINSPRD = 1
  AND B.ESTINSSRV = 1
  AND D.CODCLI NOT IN (SELECT /*PARALLEL(2) */ V.CODCLI FROM VTATABCLI V WHERE UPPER(V.NOMCLI) LIKE '%DEMO%')
  AND C.CODEQUCOM IS NULL
  AND D.CUSTOMER_ID IS NOT NULL
  AND B.FECFIN < TRUNC(SYSDATE,'DD')
ORDER BY 5 DESC
'''
