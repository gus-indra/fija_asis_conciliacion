QUERY = '''
WITH CANDIDATOS_01 AS
 (SELECT /*+ PARALLEL(4) */
   S.CUSTOMER_ID,
   S.TIPTRA,
   S.OBSERVACION,
   TO_CHAR(S.FECUSU, 'dd/mm/yyyy hh24:mi') FECHA
    FROM DMRED.SGAPRD_SOLOT S, DWS.SA_ESTSOL ES
   WHERE TRUNC(S.FECUSU) = TRUNC(SYSDATE - 1)
     AND S.ESTSOL = ES.ESTSOL
     AND ES.TIPESTSOL NOT IN (5, 7)
     AND S.CUSTOMER_ID IS NOT NULL
   GROUP BY S.CUSTOMER_ID,
            S.TIPTRA,
            S.OBSERVACION,
            TO_CHAR(S.FECUSU, 'dd/mm/yyyy hh24:mi')
  HAVING COUNT(1) > 1),
CANDIDATOS_02 AS
 (SELECT /*+ PARALLEL(4) */
   CD01.CUSTOMER_ID,
   CD01.TIPTRA,
   CD01.OBSERVACION,
   CD01.FECHA,
   (SELECT LISTAGG(SP.CODSRVNUE, ',') WITHIN GROUP(ORDER BY SP.CODSRVNUE ASC)
      FROM DMRED.SGAPRD_SOLOTPTO SP
     WHERE SP.CODSOLOT = ST.CODSOLOT) AS LIST_CODSRV
    FROM CANDIDATOS_01 CD01, DMRED.SGAPRD_SOLOT ST, DWS.SA_ESTSOL ES
   WHERE CD01.CUSTOMER_ID = ST.CUSTOMER_ID
     AND CD01.TIPTRA = ST.TIPTRA
     AND CD01.OBSERVACION = ST.OBSERVACION
     AND CD01.FECHA = TO_CHAR(ST.FECUSU, 'dd/mm/yyyy hh24:mi')
     AND ST.ESTSOL = ES.ESTSOL
     AND ES.TIPESTSOL NOT IN (5, 7)),
CANDIDATOS_03 AS
 (SELECT CD02.CUSTOMER_ID,
         CD02.TIPTRA,
         CD02.OBSERVACION,
         CD02.FECHA,
         CD02.LIST_CODSRV,
         COUNT(1) AS CANT_DUP
    FROM CANDIDATOS_02 CD02
   GROUP BY CD02.CUSTOMER_ID,
            CD02.TIPTRA,
            CD02.OBSERVACION,
            CD02.FECHA,
            CD02.LIST_CODSRV
  HAVING COUNT(1) > 1)
SELECT CD03.CUSTOMER_ID,
       CD03.TIPTRA,
       CD03.OBSERVACION,
       CD03.FECHA,
       CD03.LIST_CODSRV,
       CD03.CANT_DUP,
       CASE
         WHEN CA.CUSTOMER_ID IS NOT NULL THEN
          'AS_IS'
         WHEN BCA.CUSTOMER_ID IS NOT NULL THEN
          'TO_BE'
       END AS PLATAFORMA
  FROM CANDIDATOS_03 CD03
  LEFT JOIN DMRED.CUSTOMER_ALL CA
    ON CA.CUSTOMER_ID = CD03.CUSTOMER_ID
  LEFT JOIN DMRED.BSCSIX_CUSTOMER_ALL BCA
    ON BCA.CUSTOMER_ID = CD03.CUSTOMER_ID
'''

