QUERY = '''
WITH CLIENTE_ASIS AS
 (SELECT /*+parallel (4)*/
   CA.CUSTOMER_ID,
   CA.CO_ID,
   CA.TMCODE,
   CU.PRGCODE,
   CH.CH_STATUS,
   CH.CH_VALIDFROM
    FROM DMRED.CONTRACT_ALL CA
   INNER JOIN DM.V_CONTRACT_HISTORY CH
      ON CA.CO_ID = CH.CO_ID
   INNER JOIN DMRED.CUSTOMER_ALL CU
      ON CA.CUSTOMER_ID = CU.CUSTOMER_ID
   WHERE CH.CH_STATUS = 'a'
     AND CA.TMCODE = 1817
     AND CU.PRGCODE IN ('2', '3', '1', '5')
     AND CA.PLCODE = 79
     AND CH.CH_VALIDFROM <= TRUNC(SYSDATE - 1)),
CLIENTE_LINEA AS
 (SELECT /*+parallel (4)*/
   CAI.CUSTOMER_ID,
   CAI.CO_ID,
   CAI.TMCODE,
   CAI.PRGCODE,
   CAI.CH_STATUS,
   CAI.CH_VALIDFROM,
   '51' || DN.DN_NUM AS MSISDN_BSCS7,
   PT.PORT_NUM AS IMSI_BSCS7
    FROM DMRED.CONTR_SERVICES_CAP CSC1
   INNER JOIN DMRED.DIRECTORY_NUMBER DN
      ON DN.DN_ID = CSC1.DN_ID
   INNER JOIN CLIENTE_ASIS CAI
      ON CAI.CO_ID = CSC1.CO_ID
   INNER JOIN DMRED.CONTR_DEVICES CD
      ON CD.CO_ID = CAI.CO_ID
   INNER JOIN DMRED.PORT PT
      ON PT.PORT_ID = CD.PORT_ID
   WHERE CSC1.SEQNO = (SELECT /*+parallel (4)*/
                        MAX(CSC2.SEQNO)
                         FROM DMRED.CONTR_SERVICES_CAP CSC2
                        WHERE CSC2.CO_ID = CSC1.CO_ID)
     AND CSC1.CS_DEACTIV_DATE IS NULL
     AND CD.CD_SEQNO = (SELECT /*+parallel (4)*/
                         MAX(CD2.CD_SEQNO)
                          FROM DMRED.CONTR_DEVICES CD2
                         WHERE CD2.CO_ID = CD.CO_ID)
     AND SUBSTR(PT.PORT_NUM, 6, 1) != 9)
SELECT /*+parallel (4)*/
 CL.CUSTOMER_ID,
 CL.CO_ID,
 CL.TMCODE,
 CL.PRGCODE,
 CL.CH_STATUS,
 CL.CH_VALIDFROM,
 CL.MSISDN_BSCS7,
 CL.IMSI_BSCS7,
 HU.MSISDN            AS MSISDN_UDB,
 HU.IMSI              AS IMSI_UDB,
 HU.APNTPLID,
 HU.ROUTECATEGORY,
 HU.EPS_QOSTPL_ID,
 HU.OPTGPRS_CONTEXTID
  FROM CLIENTE_LINEA CL
 INNER JOIN DWS.SA_HLR_UDB PARTITION (P_{FECHA}) HU
    ON HU.MSISDN = CL.MSISDN_BSCS7
 WHERE REGEXP_INSTR(HU.APNTPLID, '(999)', 1, 1) > 0
'''

