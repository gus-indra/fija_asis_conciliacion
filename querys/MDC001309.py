QUERY = '''
WITH TIPTRA_CN AS
 (SELECT TTO.TIPTRA
    FROM DWS.SA_TIPTRABAJO TTO
   WHERE REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(HFC|FTTH)', 1, 1) > 0
     AND REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(CAMBIO DE NUMERO)', 1, 1) > 0),
CLIENTES_SGA AS
 (SELECT /*+parallel (4)*/
  DISTINCT ST.CUSTOMER_ID, ST.COD_ID AS CO_ID, ISV.NUMERO AS MSISDN
    FROM DMRED.SGAPRD_SOLOT ST
   INNER JOIN DWS.SA_ESTSOL EST
      ON EST.ESTSOL = ST.ESTSOL
   INNER JOIN DWS.SA_TIPTRABAJO TTO
      ON TTO.TIPTRA = ST.TIPTRA
   INNER JOIN TIPTRA_CN TTC
      ON TTC.TIPTRA = TTO.TIPTRA
   INNER JOIN DWS.SA_SOLOTPTO STP
      ON STP.CODSOLOT = ST.CODSOLOT
    LEFT JOIN DWS.SA_INSSRV ISV
      ON ISV.CODINSSRV = STP.CODINSSRV
    LEFT JOIN DWS.SA_ESTINSSRV ESV
      ON ESV.ESTINSSRV = ISV.ESTINSSRV
    LEFT JOIN DWS.SA_TYSTIPSRV TI
      ON TI.TIPSRV = ISV.TIPSRV
   WHERE ST.CUSTOMER_ID IS NOT NULL
     AND EST.ESTSOL IN (12, 29)
     AND ISV.ESTINSSRV = 1
     AND ST.CODCLI NOT IN
         (SELECT VTC.CODCLI
            FROM DWS.SA_VTATABCLI VTC
           WHERE VTC.NOMCLI LIKE '% DEMO %')
     AND TRUNC(ST.FECAPR) <= TRUNC(SYSDATE - 1)),
CLIENTES_JANUS AS
 (SELECT /*+parallel (4)*/
   PP.EXTERNAL_PAYER_ID_V AS CUSTOMER_ID, CS.MSISDN
    FROM DWS.SA_W_CONNECTIONS PARTITION(P_{FECHA}) CS
   INNER JOIN DWS.SA_W_CONNECTION_ACCOUNTS PARTITION(P_{FECHA}) CA
      ON CA.ACCOUNT_ID_N = CS.ACCOUNT_ID_N
   INNER JOIN DWS.SA_W_PAYERS PARTITION(P_{FECHA}) PP
      ON PP.PAYER_ID_N = CA.PAYER_ID_3_N
   INNER JOIN DWS.SA_W_PAYERS PARTITION(P_{FECHA}) P
      ON P.PAYER_ID_N = CA.PAYER_ID_0_N
   INNER JOIN CLIENTES_SGA CSS
      ON TO_CHAR(CSS.CUSTOMER_ID) = PP.EXTERNAL_PAYER_ID_V
   WHERE CS.STATUS_N = 1
     AND PP.PAYER_STATUS_N = 2
     AND P.PAYER_STATUS_N = 2
     AND CA.ACCOUNT_STATUS_N = 1),
CLIENTES_BSCS AS
 (SELECT /*+parallel (4)*/
   CSS.CUSTOMER_ID, DN.DN_NUM AS MSISDN, 'AS_IS' AS PLATAFORMA
    FROM DMRED.CONTR_SERVICES_CAP CSC1
   INNER JOIN DMRED.DIRECTORY_NUMBER DN
      ON DN.DN_ID = CSC1.DN_ID
   INNER JOIN CLIENTES_SGA CSS
      ON CSS.CO_ID = CSC1.CO_ID
   WHERE CSC1.SEQNO = (SELECT /*+parallel (4)*/
                        MAX(CSC2.SEQNO)
                         FROM DMRED.CONTR_SERVICES_CAP CSC2
                        WHERE CSC2.CO_ID = CSS.CO_ID)
  UNION
  SELECT /*+parallel (4)*/
   CSS.CUSTOMER_ID, BDN.DN_NUM AS MSISDN, 'TO_BE' AS PLATAFORMA
    FROM DMRED.BSCSIX_DIRECTORY_NUMBER BDN
   INNER JOIN DMRED.BSCSIX_CONTR_SERVICES_CAP BCSC
      ON BCSC.DN_ID = BDN.DN_ID
   INNER JOIN CLIENTES_SGA CSS
      ON CSS.CO_ID = BCSC.CO_ID
   WHERE BCSC.CS_DEACTIV_DATE IS NULL),
RESULTADO AS
 (SELECT /*+parallel (4)*/
   CSS.CUSTOMER_ID,
   '51' || CSS.MSISDN AS MSISDN_SGA,
   CSJ.MSISDN AS MSISDN_JANUS,
   '51' || CSB.MSISDN AS MSISDN_BSCS,
   CSB.PLATAFORMA
    FROM CLIENTES_SGA CSS
   INNER JOIN CLIENTES_JANUS CSJ
      ON CSJ.CUSTOMER_ID = TO_CHAR(CSS.CUSTOMER_ID)
   INNER JOIN CLIENTES_BSCS CSB
      ON CSB.CUSTOMER_ID = CSS.CUSTOMER_ID)
SELECT /*+parallel (4)*/
 RS.CUSTOMER_ID,
 RS.MSISDN_SGA,
 RS.MSISDN_JANUS,
 RS.MSISDN_BSCS,
 RS.PLATAFORMA
  FROM RESULTADO RS
 WHERE RS.MSISDN_SGA != RS.MSISDN_JANUS
    OR RS.MSISDN_SGA != RS.MSISDN_BSCS
    OR RS.MSISDN_JANUS != RS.MSISDN_BSCS
'''

