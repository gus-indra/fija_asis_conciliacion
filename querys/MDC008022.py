QUERY = '''
WITH TIPTRABAJO AS
 (SELECT /*+ PARALLEL (4) */
   TTO.TIPTRA, TTO.DESCRIPCION
    FROM DWS.SA_TIPTRABAJO TTO
   WHERE REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(HFC|FTTH|WLL)', 1, 1) > 0
     AND REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(SUSP|CORTE)', 1, 1) > 0
     AND REGEXP_INSTR(UPPER(TTO.DESCRIPCION), '(RECONEXI)', 1, 1) = 0
  UNION
  SELECT TTO.TIPTRA, TTO.DESCRIPCION
    FROM DWS.SA_TIPTRABAJO TTO
   WHERE TTO.TIPTRA = 349),
TIPI_SX AS
 (SELECT /*+ PARALLEL (4) */
   T.INTERACT_ID,
   T.CREATE_DATE,
   T.PHONE,
   SUBSTR(T.PHONE, 2) AS CUSTOMERID,
   T.X_SUBCLASE_CODE,
   T.REASON_3,
   T.REASON_1,
   SUBSTR(TRIM(DBMS_LOB.SUBSTR(TX.NOTES, 2000, 1)), 1, 2000) AS NOTAS,
   IT.X_INTER_1,
   IT.X_INTER_2,
   IT.X_INTER_15,
   IT.X_INTER_16,
   ROW_NUMBER() OVER(PARTITION BY T.PHONE ORDER BY T.CREATE_DATE DESC) AS ORDEN
    FROM DMRED.TABLE_INTERACT T
    LEFT JOIN DMRED.TABLE_X_PLUS_INTER IT
      ON IT.X_PLUS_INTER2INTERACT = T.OBJID
    LEFT JOIN DWS.SA_TABLE_INTERACT_TXT TX
      ON TX.INTERACT_TXT2INTERACT = T.OBJID
   WHERE T.CREATE_DATE >= ADD_MONTHS(TRUNC(SYSDATE), -1)
     AND TRUNC(T.CREATE_DATE) < (TRUNC(SYSDATE))
     AND T.X_SUBCLASE_CODE IN (350208, 270108, 350214)
     AND T.PHONE NOT LIKE '87%'
     AND (TO_DATE(REGEXP_SUBSTR(IT.X_INTER_1, {DATOS}),
                  'DD/MM/YY') < TO_DATE(SYSDATE, 'DD/MM/YY') OR
         IT.X_INTER_1 IS NULL)),
SX_SGA AS
 (SELECT /*+ PARALLEL (4) */
   S.CUSTOMER_ID,
   S.COD_ID,
   S.CODSOLOT,
   S.TIPTRA,
   T.DESCRIPCION AS TIPO_SOT,
   S.ESTSOL,
   E.DESCRIPCION,
   S.FECINI,
   S.FECFIN,
   S.FECULTEST,
   S.CODCLI,
   S.IDOAC
    FROM DMRED.SGAPRD_SOLOT S
   INNER JOIN TIPTRABAJO T
      ON T.TIPTRA = S.TIPTRA
    LEFT JOIN DWS.SA_ESTSOL E
      ON E.ESTSOL = S.ESTSOL
   WHERE TRUNC(S.FECULTEST) < SYSDATE
     AND S.IDOAC IS NULL
     AND S.ESTSOL IN (12, 29)
     AND S.CODSOLOT = (SELECT /*+ PARALLEL (4) */
                        MAX(ST.CODSOLOT)
                         FROM DMRED.SGAPRD_SOLOT ST
                        WHERE ST.CUSTOMER_ID = S.CUSTOMER_ID)),
TIPI_SX_SGA AS
 (SELECT /*+ PARALLEL (4) */
   SS.CUSTOMER_ID,
   SS.COD_ID,
   SS.CODSOLOT,
   SS.TIPTRA,
   SS.TIPO_SOT,
   SS.ESTSOL,
   SS.DESCRIPCION,
   SS.FECINI,
   SS.FECFIN,
   SS.FECULTEST,
   SS.CODCLI,
   SS.IDOAC,
   TS.X_INTER_2
    FROM TIPI_SX TS
    LEFT JOIN SX_SGA SS
      ON SS.CUSTOMER_ID = TS.CUSTOMERID
   WHERE TO_DATE(SS.FECULTEST, 'DD/MM/YY') >=
         TO_DATE(TS.X_INTER_1, 'DD/MM/YY')),
TIPI_SX_SGA_BSCS AS
 (SELECT /*+ PARALLEL (4) */
   SX.CUSTOMER_ID,
   SX.COD_ID,
   SX.CODSOLOT,
   SX.TIPTRA,
   SX.TIPO_SOT,
   SX.ESTSOL,
   SX.DESCRIPCION,
   SX.FECINI,
   SX.FECFIN,
   SX.FECULTEST,
   SX.CODCLI,
   SX.IDOAC,
   SX.X_INTER_2,
   CASE
     WHEN CH.CH_STATUS IS NOT NULL THEN
      CH.CH_STATUS
     ELSE
      CA.CH_STATUS
   END AS STATUS_CO_ID,
   CH.CH_REASON,
   CH.CH_VALIDFROM,
   CASE
     WHEN CH.CH_STATUS IS NOT NULL THEN
      'AS_IS'
     ELSE
      'TO_BE'
   END AS PLATAFORMA
    FROM TIPI_SX_SGA SX
    LEFT JOIN DM.V_CONTRACT_HISTORY CH
      ON CH.CO_ID = SX.COD_ID
    LEFT JOIN DMRED.BSCSIX_CONTRACT_ALL CA
      ON CA.CO_ID = SX.COD_ID)
SELECT /*+ PARALLEL (4) */
 A.ACCOUNTNUMBER,
 RV.RANGETEXTVALUE SERVICE_STATUS,
 ST.SERVICENAME,
 SX.CUSTOMER_ID,
 SX.COD_ID,
 SX.CODSOLOT,
 SX.TIPTRA,
 SX.TIPO_SOT,
 SX.ESTSOL,
 SX.DESCRIPCION,
 SX.FECINI,
 SX.FECFIN,
 SX.FECULTEST,
 SX.CODCLI,
 SX.IDOAC,
 SX.X_INTER_2,
 SX.STATUS_CO_ID,
 SX.CH_REASON,
 RA.RS_DESC TIPO_SUSPENSION,
 SX.CH_VALIDFROM,
 SX.PLATAFORMA
  FROM DWS.SA_ACCOUNT          PARTITION(P_{FECHA}) A,
       DWS.SA_SUBSCRIBER       PARTITION(P_{FECHA}) SU,
       DWS.SA_SERVICE          PARTITION(P_{FECHA}) S,
       DWS.SA_RANGE_VALUE      PARTITION(P_{FECHA}) RV,
       DWS.SA_SERVICE_TYPE     PARTITION(P_{FECHA}) ST,
       TIPI_SX_SGA_BSCS        SX,
       DWS.SA_REASONSTATUS_ALL RA
 WHERE SU.ACCOUNTID = A.ACCOUNTID
   AND SU.SUBSCRIBERID = S.SUBSCRIBERID
   AND S.SERVICESTATUSID = RV.RANGEVALUEID
   AND S.SERVICETYPEID = ST.SERVICETYPEID
   AND TO_CHAR(SX.CUSTOMER_ID) = A.ACCOUNTNUMBER
   AND RV.RANGENAME = 'SERVICE_STATUS_VALUES'
   AND RA.RS_ID = SX.CH_REASON
   AND SX.STATUS_CO_ID = 's'
   AND RV.RANGETEXTVALUE = 'Active'
   AND TRUNC(SX.FECULTEST) < TRUNC(SYSDATE)
   AND ST.SERVICENAME NOT IN ('FTTH_Telefonia_Servicio',
                              'FTTH_Telefonia_Servicio_Prepaid',
                              'Telefonia_Servicio_Payphone',
                              'Telefonia_Servicio_Prepaid',
                              'Telefonia_Servicio',
                              'Telefonia_Espacio',
                              'Telefonia_Suplemento',
                              'HFC_IPTVVIDEO',
                              'WIFI_PLUME',
                              'WIFI_PLUME_FTTH')
   AND EXISTS (SELECT /*+ PARALLEL (4) */
         1
          FROM DWS.SA_TAG_MAP PARTITION(P_{FECHA}) T,
               DWS.SA_TAG     PARTITION(P_{FECHA}) G
         WHERE T.OBJECTID = S.SERVICETYPEID
           AND T.TAGID = G.ID)
'''

