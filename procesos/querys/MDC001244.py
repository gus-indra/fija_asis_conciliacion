OBTENER_CUSTOMER='''
    SELECT 
    DISTINCT
    CA.CUSTOMER_ID
    FROM DMRED.CONTRACT_ALL       CA
    LEFT JOIN  (SELECT CO_ID,MAX(CH2.CH_SEQNO) CH_SEQNO
        FROM DWS.SA_CONTRACT_HISTORY CH2
    GROUP BY CH2.CO_ID )CH2
    ON CH2.CO_ID =CA.CO_ID
    LEFT JOIN DMRED.CONTRACT_HISTORY   CH
        ON CH.CO_ID = CH2.CO_ID
        AND CH.CH_SEQNO = CH2.CH_SEQNO
    LEFT JOIN DMRED.CUSTOMER_ALL       CU 
        ON CA.CUSTOMER_ID = CU.CUSTOMER_ID 
    WHERE CH.CH_PENDING IS NULL
    AND CH.CH_VALIDFROM < TRUNC(SYSDATE)                    
    AND CH.CH_STATUS = 's'
    AND CA.PLCODE = 1000
    AND CA.SCCODE = 6
    AND CU.PRGCODE IN ('1','2','5','4')
'''

