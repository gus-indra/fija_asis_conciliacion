BASE_SGA = '''
SELECT /*PARALLEL(7) */
    CASE
        WHEN UPPER(B.DESCRIPCION) LIKE '%HFC%'  THEN 'HFC'
        WHEN UPPER(B.DESCRIPCION) LIKE '%LTE%'  THEN 'LTE'
        WHEN UPPER(B.DESCRIPCION) LIKE '%FTTH%' THEN 'FTTH'
        WHEN UPPER(B.DESCRIPCION) LIKE '%DTH%'  THEN 'DTH'
        ELSE 'OTRO'
    END AS TECNOLOGIA,
    A.CUSTOMER_ID,
    A.COD_ID,
    A.CODSOLOT,
    A.TIPTRA,
    B.DESCRIPCION,
    A.ESTSOL,
    A.CODCLI,
    'APROBADA' ESTADO,
    TRUNC(A.FECUSU) FECUSU
    FROM SOLOT A
    INNER JOIN TIPTRABAJO B
            ON A.TIPTRA = B.TIPTRA
    LEFT JOIN OPERACION.SGAT_BSCSIX_CBIO E
            ON A.CODSOLOT=E.CODSOLOT
    WHERE A.ESTSOL = 11 
    AND A.FECUSU < TRUNC(SYSDATE - 1)
    AND A.FECUSU >= TO_DATE('01/01/2025','DD/MM/YYYY')
    AND B.CUENTA IS NULL
    AND A.TIPCON = 'C'
    AND A.TIPTRA NOT IN (429)
    AND E.CODSOLOT IS NULL
    AND A.TIPTRA NOT IN (1183)
'''
