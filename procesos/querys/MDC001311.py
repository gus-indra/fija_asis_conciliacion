BASE_SGA_VOD ='''SELECT DISTINCT D.CUSTOMER_ID,
                    D.COD_ID,
                    D.FECULTEST,
                    B.TIPSRV,
                    T.DSCTIPSRV,
                    C.FLGPRINC,
                    B.CODINSSRV,
                    C.CODSRV,
                    C.CODUSU,
                    E.DSCSRV,
                    C.ESTINSPRD,
                    D.TIPTRA,
                    R.DESCRIPCION,
                    F.CODIGO_EXT
    FROM SOLOTPTO A
    INNER JOIN SOLOT D
        ON A.CODSOLOT = D.CODSOLOT
    INNER JOIN INSSRV B
        ON B.CODINSSRV = A.CODINSSRV
    INNER JOIN INSPRD C
        ON C.PID = A.PID
    INNER JOIN TYSTABSRV E
        ON E.CODSRV = C.CODSRV
    INNER JOIN TYSTABSRV J
        ON J.CODSRV = B.CODSRV
    LEFT JOIN TYSTIPSRV T
        ON B.TIPSRV = T.TIPSRV
    LEFT JOIN TIPTRABAJO R
        ON D.TIPTRA = R.TIPTRA
    LEFT JOIN INTRAWAY.CONFIGURACION_ITW F
        ON F.IDCONFIGITW = E.CODIGO_EXT
    WHERE C.FLGPRINC = 0
    AND B.ESTINSSRV = 1
    AND C.ESTINSPRD = 1
    AND D.CODCLI NOT IN
        (SELECT V.CODCLI
            FROM VTATABCLI V
            WHERE UPPER(V.NOMCLI) LIKE '%DEMO%')
    AND C.CODEQUCOM IS NULL
    AND D.CUSTOMER_ID IS NOT NULL
    AND UPPER(R.DESCRIPCION) LIKE '%HFC%'
    AND C.CODSRV = 'AEFF'
    AND D.ESTSOL <> 17
    ORDER BY 5 DESC
'''
