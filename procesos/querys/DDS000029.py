EJECT_BSCS= '''
 SELECT CA.CUSTOMER_ID
  FROM DMRED.PR_SERV_STATUS_HIST SH
 INNER JOIN DMRED.PROFILE_SERVICE PS
    ON PS.CO_ID = SH.CO_ID
   AND PS.SNCODE = SH.SNCODE
   AND PS.STATUS_HISTNO = SH.HISTNO
 INNER JOIN DMRED.MPUSNTAB MP
    ON SH.SNCODE = MP.SNCODE
  LEFT JOIN DMRED.CONTRACT_ALL CA
    ON SH.CO_ID = CA.CO_ID
  LEFT JOIN DM.V_CONTRACT_HISTORY CH
    ON CH.CO_ID = CA.CO_ID
  LEFT JOIN DMRED.CUSTOMER_ALL CU
    ON CU.CUSTOMER_ID = CA.CUSTOMER_ID
 WHERE CA.PLCODE = 1000
   AND CA.SCCODE = 6
   AND CH.CH_STATUS IN('a')
  --- AND CA.CUSTOMER_ID IN (SELECT * FROM CUSTOMER)
   AND CU.PRGCODE IN ('2', '5')
   AND CH.CH_VALIDFROM < TRUNC(SYSDATE)
   AND SH.STATUS IN ('A', 'S')
   AND UPPER(MP.DES) LIKE '%WIFI%'
'''

