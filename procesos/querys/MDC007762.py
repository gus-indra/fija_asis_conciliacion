GENERAR_BASE = '''
    WITH BASE_CICLO_JANUS AS
    (SELECT DISTINCT C.MSISDN, SUBSTR(PBCD.BILL_CYCLE_N, 2, 2) CICLO
        FROM DWS.SA_W_CONNECTIONS PARTITION(P_{FECHA}) C
    INNER JOIN DWS.SA_W_CONNECTION_ACCOUNTS PARTITION(P_{FECHA}) CA
        ON C.ACCOUNT_ID_N = CA.ACCOUNT_ID_N
    INNER JOIN DWS.SA_W_PAYERS PARTITION(P_{FECHA}) P
        ON P.PAYER_ID_N = GREATEST(PAYER_ID_0_N, PAYER_ID_3_N)
    INNER JOIN DWS.SA_W_PAYER_BILL_CYCLE_DETAILS PARTITION(P_{FECHA}) PBCD
        ON P.PAYER_ID_N = PBCD.PAYER_ID_N
    INNER JOIN DWS.SA_W_PAYER_WALLETS PARTITION(P_{FECHA}) PW
        ON P.PAYER_ID_N = PW.PAYER_ID_N
    WHERE PW.WALLET_ID_N = 6),

    BASE AS
    (SELECT /*+PARALLEL(4)*/
    CA.CUSTOMER_ID,
    CH.CO_ID,
    CH.CH_STATUS,
    CA.TMCODE,
    CU.BILLCYCLE,
    51 || DN.DN_NUM DN_NUM
        FROM DMRED.CONTRACT_HISTORY CH
    INNER JOIN DMRED.CONTRACT_ALL CA
        ON CH.CO_ID = CA.CO_ID
    INNER JOIN DMRED.CUSTOMER_ALL CU
        ON CA.CUSTOMER_ID = CU.CUSTOMER_ID
    INNER JOIN (SELECT CO_ID, MAX(CH_SEQNO) CH_SEQNO
                    FROM DMRED.CONTRACT_HISTORY
                GROUP BY CO_ID) CH2
        ON CH.CO_ID = CH2.CO_ID
        AND CH2.CH_SEQNO = CH.CH_SEQNO
    INNER JOIN DMRED.CONTR_SERVICES_CAP CS
        ON CA.CO_ID = CS.CO_ID
    INNER JOIN (SELECT CO_ID, MAX(SEQNO) SEQNO
                    FROM DMRED.CONTR_SERVICES_CAP
                GROUP BY CO_ID) CS2
        ON CS2.CO_ID = CS.CO_ID
        AND CS.SEQNO = CS2.SEQNO
    INNER JOIN DMRED.DIRECTORY_NUMBER DN
        ON CS.DN_ID = DN.DN_ID
    WHERE NOT ((LENGTH(CU.BILLCYCLE) > 1 AND CU.BILLCYCLE LIKE '9%'))
        AND CH.CH_STATUS = 'a'
        AND CU.PRGCODE IN ('1', '2', '5')
        AND CA.PLCODE = 1000
        AND CH.CH_PENDING IS NULL
        AND CS.CS_DEACTIV_DATE IS NULL
        AND CA.SCCODE = 6)

    SELECT /*+ PARALLEL (7) */
    H.CUSTOMER_ID,
    H.CO_ID,
    H.DN_NUM,
    H.BILLCYCLE   CICLO_BSCS,
    C.CICLO       CICLO_JANUS
    FROM BASE H, BASE_CICLO_JANUS C
    WHERE TO_CHAR(H.DN_NUM) = TO_CHAR(C.MSISDN)
    AND TO_CHAR(H.BILLCYCLE) <> TO_CHAR(C.CICLO)
'''

