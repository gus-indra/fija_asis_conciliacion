QUERY_OUT_PLUME = '''
SELECT DISTINCT A.CUSTOMER_ID,
                A.COD_ID CO_ID,
                C.ESTINSSRV,
                D.ESTINSPRD,
                A.CODCLI,
                E.DSCSRV,
                F.DSCTIPSRV,
                E.TIPSRV,
                D.CODEQUCOM,
                SL.DESMAT,
                SL.TIPO_EQU_PROV
  FROM SOLOT A
 INNER JOIN SOLOTPTO B
    ON A.CODSOLOT = B.CODSOLOT
 INNER JOIN INSSRV C
    ON B.CODINSSRV = C.CODINSSRV
 INNER JOIN INSPRD D
    ON D.CODINSSRV = c.CODINSSRV
  LEFT JOIN TYSTABSRV E
    ON E.CODSRV = D.CODSRV
  LEFT JOIN TYSTIPSRV F
    ON C.TIPSRV = F.TIPSRV
  LEFT JOIN INTRAWAY.CONFIGURACION_ITW BB
    ON TO_CHAR(BB.IDCONFIGITW) = E.CODIGO_EXT
  LEFT JOIN VTAEQUCOM VV
    ON D.CODEQUCOM=VV.CODEQUCOM 
  LEFT JOIN EQUCOMXOPE XO
    ON XO.CODEQUCOM =VV.CODEQUCOM
  LEFT JOIN PRODUCCION.ALMTABMAT SL
    ON SL.CODMAT = XO.CODTIPEQU
 WHERE C.ESTINSSRV in (1,2)
   AND D.ESTINSPRD in (1,2)
   AND A.CODCLI NOT IN
       (SELECT V.CODCLI
          FROM VTATABCLI V
         WHERE UPPER(V.NOMCLI) LIKE '% DEMO %')
   AND A.CUSTOMER_ID IS NOT NULL
   AND SL.TIPO_EQU_PROV ='PLUME'
   AND E.DSCSRV LIKE '%Alquiler de Equipos INT%'
'''

